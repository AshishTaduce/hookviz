#!/usr/bin/env tsx
/**
 * Prebuild script: globs recorder/out/*.trace.json and writes the static
 * catalog array into web/lib/catalog.ts.
 *
 * Run: tsx lib/generate-catalog.ts (from web/ directory)
 * Or:  npm run prebuild (in web/)
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join, resolve } from 'path';

const outDir = resolve(process.cwd(), '../recorder/out');
const catalogPath = resolve(process.cwd(), 'lib/catalog.ts');

const files = readdirSync(outDir)
  .filter((f) => f.endsWith('.trace.json'))
  .sort();

type Entry = { id: string; title: string; hook: string; category: string };

const entries: Entry[] = files.map((file) => {
  const raw = JSON.parse(readFileSync(join(outDir, file), 'utf8'));
  return {
    id: raw.meta.id as string,
    title: raw.meta.title as string,
    hook: raw.meta.hook as string,
    category: raw.meta.category as string,
  };
});

const code = `import type { CatalogEntry } from '@/types/trace';

// AUTO-GENERATED by lib/generate-catalog.ts — do not edit by hand.
// Re-run: npm run prebuild (in web/)
const catalog: CatalogEntry[] = ${JSON.stringify(entries, null, 2)};

export default catalog;

export const DEFAULT_TRACE_ID = catalog[0].id;
`;

writeFileSync(catalogPath, code);
console.log(`Wrote ${entries.length} entries to lib/catalog.ts`);
